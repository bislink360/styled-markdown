// Writes the JetBrains plugin's TextMate grammar, bundle/syntaxes/smd.tmLanguage.json, from the VS Code extension's.
//
//   node integrations/jetbrains/scripts/bundle-grammar.mjs          write it
//   node integrations/jetbrains/scripts/bundle-grammar.mjs --check  fail when the committed file is out of date
//
// The extension highlights .smd with two grammars: smd.tmLanguage.json (front matter, then Markdown) and
// smd-directives.injection.json, which VS Code injects into it (package.json `injectTo`). JetBrains' TextMate support
// reads a VS Code bundle's `embeddedLanguages` but not `injectTo`, so the injection never applied there. It does apply
// a grammar's own `injections`. So the plugin's grammar is the extension's, with the injection grammar's rules as its
// own `injections` and its rules added to its repository. It includes the plugin's copy of the Markdown grammar
// (bundle/syntaxes/markdown.tmLanguage.json, scope text.html.markdown.smd) instead of the IDE's text.html.markdown,
// whose bundle an IDE may have turned off.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const out = join(here, '..', 'bundle', 'syntaxes', 'smd.tmLanguage.json');

/** The scope of the plugin's copy of the Markdown grammar. */
export const MARKDOWN_SCOPE = 'text.html.markdown.smd';

/** The plugin's grammar, as the text of the JSON file. */
export function bundleGrammar() {
  const read = (file) => JSON.parse(readFileSync(join(root, 'extension', 'syntaxes', file), 'utf8'));
  const main = read('smd.tmLanguage.json');
  const injection = read('smd-directives.injection.json');
  const repository = { ...main.repository };
  for (const [name, rule] of Object.entries(injection.repository ?? {})) {
    if (name in repository) throw new Error(`Both grammars have a rule named ${name}: rename one.`);
    repository[name] = rule;
  }
  const patterns = main.patterns.map((p) => (p.include === 'text.html.markdown' ? { include: MARKDOWN_SCOPE } : p));
  if (!patterns.some((p) => p.include === MARKDOWN_SCOPE)) throw new Error('smd.tmLanguage.json no longer includes text.html.markdown');
  const grammar = {
    information_for_contributors: [
      'Generated by integrations/jetbrains/scripts/bundle-grammar.mjs from extension/syntaxes: do not edit.',
      'It is smd.tmLanguage.json with the rules of smd-directives.injection.json as its own injections.',
    ],
    name: main.name,
    scopeName: main.scopeName,
    patterns,
    injections: { [injection.injectionSelector]: { patterns: injection.patterns } },
    repository,
  };
  return `${JSON.stringify(grammar, null, 2)}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = bundleGrammar();
  if (process.argv.includes('--check')) {
    if (readFileSync(out, 'utf8') !== text) {
      console.error(`${out} is out of date: run node integrations/jetbrains/scripts/bundle-grammar.mjs`);
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${out}`);
  }
}
